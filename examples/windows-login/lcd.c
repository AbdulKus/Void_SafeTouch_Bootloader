static void spi(uint8_t value)
{
    for (unsigned bit = 0; bit < 8; ++bit) {
        if (value & 0x80u) PIO_SODR = LCD_MOSI; else PIO_CODR = LCD_MOSI;
        PIO_SODR = LCD_CLK; PIO_CODR = LCD_CLK; value <<= 1;
    }
}
static void command(uint8_t value) { PIO_CODR=LCD_CS|LCD_A0; spi(value); PIO_SODR=LCD_CS; }
static void data(uint8_t value) { PIO_CODR=LCD_CS; PIO_SODR=LCD_A0; spi(value); PIO_SODR=LCD_CS; }
static const uint8_t *glyph_for(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (unsigned i=0; i<sizeof(font)/sizeof(font[0]); ++i) if(font[i].character==c) return font[i].columns;
    return font[0].columns;
}
static void line(unsigned page, const char *text)
{
    command((uint8_t)(0xB0u|page)); command(0x10); command(0);
    unsigned written=0;
    while (*text && written+6u<=132u) {
        const uint8_t *g=glyph_for(*text++); for(unsigned i=0;i<5;++i)data(g[i]); data(0); written+=6;
    }
    while(written++<132u)data(0);
}
void lcd_init(void)
{
    PIO_PER=LCD_MASK|BACKLIGHT; PIO_OER=LCD_MASK|BACKLIGHT; PIO_SODR=LCD_CS|LCD_RST|BACKLIGHT;
    PIO_CODR=LCD_A0|LCD_CLK|LCD_MOSI; PIO_CODR=LCD_RST; delay(2000); PIO_SODR=LCD_RST; delay(2000);
    command(0xAE);command(0xA2);command(0xA1);command(0xC0);command(0x40);command(0x2F);delay(10000);
    command(0x27);command(0x81);command(0x04);command(0xA6);command(0xA4);command(0xAF);
    for(unsigned p=0;p<8;++p)line(p,"");
}
void lcd_screen(const char *line1, const char *line2, const char *line3)
{
    line(1,line1); line(3,line2); line(5,line3); line(7,"");
}
